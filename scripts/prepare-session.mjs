import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomBytes,createHash} from 'node:crypto';
import {validateConfig} from '../core.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const configPath=path.resolve(root,process.argv[2]||'config/clase21.json');
const config=validateConfig(JSON.parse(fs.readFileSync(configPath,'utf8')));
const access=path.join(root,'entregables',`ACCESO-DOCENTE-${config.id}.txt`),sql=path.join(root,'entregables',`activar-${config.id}.sql`);
if(fs.existsSync(access)||fs.existsSync(sql))throw Error('Ya existen archivos privados para esta sesión. Conservá esa clave; no los sobrescribas.');
const key=randomBytes(24).toString('hex'),hash=createHash('sha256').update(key).digest('hex');
const base='https://gsolovey-utdt.github.io/decisiones/';
const student=`${base}index.html?s=${config.id}`,teacher=`${base}admin.html?s=${config.id}&v=panel#${key}`;
fs.mkdirSync(path.dirname(access),{recursive:true});
fs.writeFileSync(access,`ACCESO PRIVADO · NO SUBIR A GITHUB\n\nEstudiantes: ${student}\nDocente: ${teacher}\nClave: ${key}\n\nCada vista se abre cambiando v; los enlaces del panel conservan la clave.\nActivación: ejecutar activar-${config.id}.sql completo en el SQL Editor del proyecto irryksaoygdklwtsjsru. La recepción empieza cerrada.\n`);
const payload=JSON.stringify(config).replace(/'/g,"''");
const schema=fs.readFileSync(path.join(root,'schema.sql'),'utf8');
fs.writeFileSync(sql,`begin;\n${schema}\n\ninsert into public.nype_dec_sessions(id,config,key_hash) values ('${config.id}','${payload}'::jsonb,'${hash}');\ncommit;\n-- Sesión creada, recepción cerrada. Abrí el panel privado y tocá Abrir recepción.\n`);
console.log(`Generados entregables/activar-${config.id}.sql y entregables/ACCESO-DOCENTE-${config.id}.txt (privados, ignorados por Git).`);
